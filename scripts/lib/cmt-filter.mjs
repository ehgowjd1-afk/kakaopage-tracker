// 댓글 분석에서 뺄 댓글 (회차별 댓글 수에는 그대로 센다 — 사용자 지시 2026-10-11)
//
// 1) 작가·그림 작가·출판사의 인사·공지 ("안녕하세요, ○○입니다", "작화를 맡은 ○○입니다") — 주로 1화에 있다.
//    닉네임이 작가 이름과 같은 댓글은 부르는 쪽에서 따로 거른다(닉네임은 거르는 데만 쓰고 버림).
// 2) 내용 없는 댓글 — 인사·수고·감사·등수·출석·한 단어 감탄('웅장', '수고하셨습니다', '1등', '재밌어요'만 있는 것).
//    무엇이 좋은지·싫은지 말이 없어 반응 분석에 쓸 것이 없다.

export const AUTHOR_NOTE = /작가입니다|글쓴이\s?\S{1,12}입니다|(작화|각색|글|그림|채색|콘티|선화)\s?(파트|부분)?[을를]?\s?(담당|맡)|맡은\s?\S{1,12}입니다|출간한\s?\S{1,20}입니다|출판사입니다|편집(부|자)입니다|(미디어|출판|스튜디오|에이전시|엔터|컴퍼니|담당자)\S{0,3}입니다|^\s*안녕하세요[\s,.!~]*(?:독자\s?여러분[\s,.!~]*)?\S{1,20}\s?입니다/;

// 내용 없는 댓글: 아래 조각과 문장부호·웃음·이모티콘 자리표시만으로 이루어진 것
const FILLER_PART = [
  '웅장(?:하다|해진다|해짐|합니다)?', '가슴이\\s?웅장(?:해진다|해짐)?',
  '수고(?:하셨습니다|하셨어요|하셨네요|많으셨습니다|많으셨어요|했어요|하세요)?', '고생(?:하셨습니다|하셨어요|많으셨습니다|많으셨어요)',
  '감사(?:합니다|해요|드립니다)?', '고맙습니다', '잘\\s?(?:봤습니다|봤어요|보고\\s?갑니다|보고\\s?가요|읽었습니다|읽고\\s?갑니다)',
  '\\d+\\s?등', '일등', '출석', '출첵', '도장\\s?쾅?', '(?:화이팅|파이팅|홧팅)', '응원(?:합니다|해요|할게요)?',
  '작가님', '사랑(?:합니다|해요)', '최고(?:예요|에요|다|입니다)?', '재밌(?:어요|다|네요|습니다)', '재미있(?:어요|다|네요|습니다)',
  '좋아요', '좋다', '굿', '대박', '미쳤다', '와', '오', '헐', '흑', 'good', 'nice', 'wow', '정주행\\s?중', '복습\\s?중',
];
const FILLER = new RegExp(`^(?:[\\s.,!?~^*;:\\-ㅋㅎㅠㅜㄷㄱㅇㅡ♡♥❤💕👍🙏😭😊🔥]|\\(이모티콘\\)|${FILLER_PART.join('|')})+$`, 'iu');

export function isFiller(text) {
  const t = String(text || '').trim();
  if (!t) return true;
  return FILLER.test(t);
}

// 분석에 쓸 댓글인가 (작가 인사도 아니고 내용도 있음)
export const analysable = (text) => !AUTHOR_NOTE.test(String(text || '')) && !isFiller(text);
